import { supabaseAdmin } from './supabaseAdmin';

// Сколько минут ждём оплату сгенерированного адреса, прежде чем считать
// депозит просроченным (status: 'expired'). Должно совпадать с
// DEPOSIT_EXPIRY_MINUTES в webapp/js/config.js основного Mini App — если
// меняешь одно, поменяй и другое (используется и для отображения таймера
// на клиенте, и для реального тайм-аута ниже).
export const DEPOSIT_EXPIRY_MINUTES = 30;

/**
 * Массово помечает 'expired' все pending-депозиты старше
 * DEPOSIT_EXPIRY_MINUTES. Раньше это делал ТОЛЬКО внешний cron
 * (cron-job.org, см. worker.ts + README) — если его забыли настроить,
 * или он молча перестал стучаться (бесплатные крон-сервисы это иногда
 * делают сами по себе), депозит так и висел в pending навсегда: ничего
 * больше в коде не проверяло старые записи само по себе, кнопка
 * "Проверить" помогает только тому депозиту, который открыт прямо
 * сейчас в конкретном чате.
 *
 * Теперь эта функция дополнительно вызывается "по пути" из create.ts
 * (перед созданием НОВОГО депозита) и list.ts (при каждой загрузке
 * дашборда) — то есть просрочка происходит как побочный эффект обычного
 * использования сервиса, а не только по внешнему расписанию. Внешний
 * cron (worker.ts) можно оставить как есть — он просто станет одним из
 * НЕСКОЛЬКИХ путей, которыми чистятся старые депозиты, а не единственным.
 *
 * Не бросает исключения наружу — просрочка старых депозитов не должна
 * ронять запрос, ради которого её вызвали (создание нового платежа,
 * загрузка списка и т.д.), поэтому ошибка просто логируется.
 */
export async function expireStaleDeposits(): Promise<void> {
  if (!supabaseAdmin) return;
  try {
    const cutoff = new Date(Date.now() - DEPOSIT_EXPIRY_MINUTES * 60 * 1000).toISOString();
    const { error } = await supabaseAdmin
      .from('deposits')
      .update({ status: 'expired' })
      .eq('status', 'pending')
      .lt('created_at', cutoff);
    if (error) {
      console.error('[expireStaleDeposits] ошибка массовой просрочки:', error);
    }
  } catch (e) {
    console.error('[expireStaleDeposits] неожиданная ошибка:', e);
  }
}
